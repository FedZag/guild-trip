-- Index des Tagesspruchs: Tag + fester Versatz je Charakter (Name-Realm)
function ONE.QuipIndex(day, who, count)
    local h = 0
    for i = 1, #(who or "") do h = (h * 31 + who:byte(i)) % 100003 end
    return (day + h) % count + 1
end
